/** The raw and the cooked BLS food for an ingredient id (the same code twice when cooking hardly matters). */
export function ingredientFoods(id: string): readonly [raw: string, cooked: string] | undefined {
  const f = INGREDIENT_FOODS[id];
  return f === undefined ? undefined : typeof f === 'string' ? [f, f] : f;
}
