#!/usr/bin/env python3
"""
Build the offline list of German Open Food Facts products for name search (docs/SPEC.md, "Find
packaged products by name"). Run by hand now and then, not in CI: it reads Open Food Facts' Parquet
export on Hugging Face (several GB; DuckDB fetches only the columns it needs, ~4 minutes).

    pip install duckdb
    python3 scripts/off-products.py            # or: python3 scripts/off-products.py food.parquet

Writes public/data/off-products-de-<date>.tsv.gz (committed) and src/foods/offIndexInfo.ts, and
removes older lists. Only what search needs is kept: barcode, name, brand, pack size. The label
values are fetched by barcode when a product is picked, so they are always current.

Why a bundled list: Open Food Facts' name search does not answer browser apps (no CORS for other
sites; the legacy search answers 503 to anonymous users). See docs/OPEN_QUESTIONS.md.
"""
import datetime
import gzip
import pathlib
import re
import sys

import duckdb

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = 'https://huggingface.co/datasets/openfoodfacts/product-database/resolve/main/food.parquet'


def clean(s):
    return re.sub(r'\s+', ' ', s or '').strip()


def pick_name(names):
    """German first (what the package says in Germany), then the product's main language, then English."""
    by_lang = {n['lang']: clean(n['text']) for n in names or [] if clean(n['text'])}
    for lang in ('de', 'main', 'en'):
        if by_lang.get(lang):
            return by_lang[lang]
    return next(iter(by_lang.values()), '')


def pick_brand(brands):
    seen, out = set(), []
    for b in (clean(x) for x in (brands or '').split(',')):
        if b and b.lower() not in seen:
            seen.add(b.lower())
            out.append(b)
    return ', '.join(out)


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else SOURCE
    con = duckdb.connect()
    if source.startswith('http'):
        con.execute('INSTALL httpfs; LOAD httpfs;')
    # Sold in Germany, not obsolete, with an energy value on the label (a product without label values
    # cannot be logged). Most-scanned first: search shows the first matches, so popular products lead.
    rows = con.execute(
        f"""
        SELECT code, product_name, brands, quantity
        FROM read_parquet('{source}')
        WHERE list_contains(countries_tags, 'en:germany')
          AND NOT coalesce(obsolete, false)
          AND NOT coalesce(no_nutrition_data, false)
          AND len(list_filter(nutriments, lambda n: n.name IN ('energy-kcal', 'energy') AND n."100g" IS NOT NULL)) > 0
        ORDER BY coalesce(unique_scans_n, 0) DESC, coalesce(completeness, 0) DESC, code
        """
    ).fetchall()

    lines, codes = [], set()
    for code, names, brands, quantity in rows:
        code = clean(code)
        name = pick_name(names)
        if not re.fullmatch(r'\d{8,14}', code) or code in codes or not name:
            continue
        codes.add(code)
        lines.append('\t'.join(x.replace('\t', ' ') for x in (code, name, pick_brand(brands), clean(quantity))))

    day = datetime.date.today().isoformat()
    out_dir = ROOT / 'public' / 'data'
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob('off-products-de-*.tsv.gz'):
        old.unlink()
    out = out_dir / f'off-products-de-{day}.tsv.gz'
    header = f'# Open Food Facts products sold in Germany, {day}. Data: Open Food Facts contributors, ODbL. Columns: barcode, name, brand, quantity.'
    with gzip.open(out, 'wb', compresslevel=9) as f:
        f.write(('\n'.join([header, *lines]) + '\n').encode('utf-8'))

    (ROOT / 'src' / 'foods' / 'offIndexInfo.ts').write_text(
        '// Generated by scripts/off-products.py; do not edit.\n'
        f"export const OFF_INDEX = {{ file: 'data/{out.name}', date: '{day}', count: {len(lines)} }} as const;\n"
    )
    print(f'{len(lines)} products → {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
