/**
 * Writes src/ui/foodIconData.ts: the Fluent Emoji Flat pictures (Microsoft, MIT licence; from the
 * npm package @iconify-json/fluent-emoji-flat) for the icons src/logic/foodIcons.ts can pick, and
 * nothing else, so only those few KB are bundled. Run `npm run icons` after changing the word list.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { FOOD_ICON_NAMES } from '../src/logic/foodIcons';

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/fluent-emoji-flat/icons.json'), 'utf8')) as {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
};
const out: Record<string, string> = {};
for (const name of [...FOOD_ICON_NAMES].sort()) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Fluent Emoji Flat has no icon "${name}"`);
  const w = icon.width ?? set.width ?? 32;
  const h = icon.height ?? set.height ?? 32;
  out[name] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${icon.body}</svg>`;
}
const file = `/**
 * Food pictures for the kitchen tiles: Fluent Emoji Flat by Microsoft (https://github.com/microsoft/fluentui-emoji),
 * MIT licence, Copyright (c) Microsoft Corporation. Generated by scripts/food-icons.ts; do not edit.
 */
import type { FoodIconName } from '../logic/foodIcons';

export const FOOD_ICON_SVG: Record<FoodIconName, string> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('../src/ui/foodIconData.ts', import.meta.url), file);
console.log(`Wrote ${Object.keys(out).length} icons, ${(file.length / 1024).toFixed(0)} KB → src/ui/foodIconData.ts`);
